"""
backend/pipelines/pipelines.py

Every pipeline follows the same shape:
  1. try the real GPU model
  2. on GeoChatUnavailable / missing checkpoint / any load-time error,
     degrade to the deterministic fallback IF FLAGS.allow_*_fallback,
     else re-raise
  3. always run the deterministic geospatial engine on whatever pixel
     output was produced (real or fallback) -- geometry math is never
     itself a fallback, it's the trusted core
  4. wrap everything in an EvidenceContract via ProvenanceTracer
"""
from __future__ import annotations

from typing import Optional

from PIL import Image
import numpy as np

from backend.config.settings import PATHS, FLAGS
from backend.geospatial import engine as geo
from backend.evidence.contract import (
    ProvenanceTracer, build_evidence, compute_reliability, gsd_rating,
)
from backend.models.geochat.adapter import GeoChatAdapter, GeoChatUnavailable
from backend.models.changenet.model import (
    load_changenet, changenet_infer, classical_change_fallback, otsu_threshold,
)
from backend.models.dofa.adapter import DOFAAdapter, classical_fusion_fallback, BandMap


# ---------------------------------------------------------------------------
# 1. Single-image VQA
# ---------------------------------------------------------------------------

def run_vqa(image_path: str, question: str) -> dict:
    tracer = ProvenanceTracer()
    with tracer.timed("read_raster_info"):
        info = geo.read_raster_info(image_path)

    is_real, fallback_used, answer, model_conf = True, False, None, 0.8
    with tracer.timed("geochat_vqa_inference"):
        try:
            adapter = GeoChatAdapter()
            adapter.load()
            img = Image.open(image_path).convert("RGB")
            result = adapter.answer_vqa(img, question)
            adapter.unload()
            answer = result["answer"]
            model_conf = 0.85
        except GeoChatUnavailable as e:
            if not FLAGS.allow_geochat_fallback:
                raise
            is_real, fallback_used = False, True
            answer, model_conf = _vqa_heuristic_fallback(image_path, question), 0.4

    reliability, factors = compute_reliability(
        model_confidence=model_conf, registration_quality=1.0,
        gsd_resolution_rating=gsd_rating(info.gsd_x, "vqa"), fallback_used=fallback_used,
    )
    evidence = build_evidence(
        task="visual_question_answering", model="GeoChat-7B (4-bit NF4)" if is_real else "Heuristic band-statistics fallback",
        is_real_weights=is_real, fallback_used=fallback_used,
        inputs=[image_path], claim=answer, spatial_evidence=None,
        metrics={"gsd_m_per_px": round(info.gsd_x, 3)},
        reliability_score=reliability, reliability_factors=factors, tracer=tracer,
        warnings=[] if is_real else ["GeoChat checkpoint unavailable -- answer generated by "
                                      "deterministic band-statistics heuristic, not a VLM."],
    )
    return evidence.to_dict()


def _vqa_heuristic_fallback(image_path: str, question: str) -> str:
    """No language model available -- describes coarse scene statistics
    (brightness, band means, apparent water/vegetation fraction) rather
    than fabricating a free-text answer to an arbitrary question."""
    arr = geo.read_raster_array(image_path)
    band_means = arr.mean(axis=(1, 2))
    bright = float(arr.mean())
    return (
        f"[Fallback -- no GeoChat weights loaded] Cannot answer open-ended "
        f"question '{question}' without the VLM. Scene statistics: mean "
        f"brightness={bright:.1f}, per-band means={np.round(band_means, 1).tolist()}, "
        f"shape={arr.shape}. Load a GeoChat-7B checkpoint for real answers."
    )


