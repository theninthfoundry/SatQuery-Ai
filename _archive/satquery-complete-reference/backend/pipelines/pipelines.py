# 3. Grounding -> ground area
# ---------------------------------------------------------------------------

def run_grounding(image_path: str, referring_expression: str) -> dict:
    tracer = ProvenanceTracer()
    with tracer.timed("read_raster_info"):
        info = geo.read_raster_info(image_path)

    is_real, fallback_used, model_conf = True, False, 0.8
    with tracer.timed("geochat_grounding_inference"):
        try:
            adapter = GeoChatAdapter()
            adapter.load()
            img = Image.open(image_path).convert("RGB")
            result = adapter.ground(img, referring_expression)
            adapter.unload()
            bbox_norm = result["bbox_norm_ymin_xmin_ymax_xmax"]
        except GeoChatUnavailable:
            if not FLAGS.allow_geochat_fallback:
                raise
            is_real, fallback_used, model_conf = False, True, 0.35
            bbox_norm = _grounding_heuristic_fallback(image_path, referring_expression)

    with tracer.timed("denormalize_bbox"):
        bbox_px = geo.denormalize_bbox(bbox_norm, info.width, info.height)
        ymin, xmin, ymax, xmax = bbox_px

    with tracer.timed("affine_polygonization_and_area"):
        ring_native = geo.bbox_pixels_to_geo_polygon(info.transform, ymin, xmin, ymax, xmax)
        area_info = geo.geo_polygon_to_ground_area(ring_native, info.crs_epsg)

    feature_collection = {
        "type": "FeatureCollection",
        "features": [{
            "type": "Feature",
            "properties": {"referring_expression": referring_expression, **{
                k: v for k, v in area_info.items() if k != "utm_ring"}},
            "geometry": {"type": "Polygon", "coordinates": [[[round(x, 6), round(y, 6)] for x, y in ring_native]]},
        }],
    }

    reliability, factors = compute_reliability(
        model_confidence=model_conf, registration_quality=1.0,
        gsd_resolution_rating=gsd_rating(info.gsd_x, "grounding"), fallback_used=fallback_used,
    )
    claim = (
        f"Located '{referring_expression}' covering {area_info['area_m2']:,.0f} m² "
        f"({area_info['area_ha']:.2f} ha)."
    )
    evidence = build_evidence(
        task="visual_grounding", model="GeoChat-7B (4-bit NF4) + Affine Geometry Engine" if is_real
        else "Saliency-heuristic grounding + Affine Geometry Engine",
        is_real_weights=is_real, fallback_used=fallback_used,
        inputs=[image_path], claim=claim, spatial_evidence=feature_collection,
        metrics=area_info, reliability_score=reliability, reliability_factors=factors, tracer=tracer,
        warnings=[] if is_real else ["No GeoChat checkpoint -- bounding box from a generic "
                                      "saliency heuristic, not text-grounded localization."],
    )
    return evidence.to_dict()


def _grounding_heuristic_fallback(image_path: str, referring_expression: str) -> list:
    """No VLM available -- returns the bounding box of the single largest
    high-contrast connected region as a coarse saliency proxy. Honest
    about being untargeted (ignores the referring expression's semantics)."""
    arr = geo.read_raster_array(image_path)
    gray = arr.mean(axis=0)
    thresh = np.percentile(gray, 90)
    mask = (gray >= thresh).astype(np.uint8)
    ys, xs = np.where(mask)
    if len(ys) == 0:
        h, w = gray.shape
        return [400, 400, 600, 600]  # normalized-1000 center box, last resort
    ymin, ymax, xmin, xmax = ys.min(), ys.max(), xs.min(), xs.max()
    h, w = gray.shape
    return [ymin / h * 1000, xmin / w * 1000, ymax / h * 1000, xmax / w * 1000]


