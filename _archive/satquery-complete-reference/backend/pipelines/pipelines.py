def run_golden_mission_urban_expansion(image_t1: str, image_t2: str, query: str) -> dict:
    """Combines change detection with a narrative summary suitable for
    the PDF dossier exporter. Thin orchestration on top of
    run_change_detection so the golden-mission demo and the general
    change-VQA path share one source of truth."""
    result = run_change_detection(image_t1, image_t2, query=query)
    result["task"] = "golden_mission_urban_expansion"
    return result
