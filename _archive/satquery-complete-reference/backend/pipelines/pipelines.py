# 4. Bi-temporal change detection / change-VQA
# ---------------------------------------------------------------------------

def run_change_detection(image_t1: str, image_t2: str, query: Optional[str] = None,
                          threshold: Optional[float] = None) -> dict:
    tracer = ProvenanceTracer()
    with tracer.timed("read_raster_info"):
        info_t1 = geo.read_raster_info(image_t1)
        info_t2 = geo.read_raster_info(image_t2)

    with tracer.timed("validate_temporal_pair"):
        pair_check = geo.validate_bitemporal_pair(info_t1, info_t2)
        if not pair_check.is_valid:
            raise ValueError(f"Bi-temporal pair failed validation: {pair_check.reasons}")

    with tracer.timed("read_raster_arrays"):
        arr_t1 = geo.read_raster_array(image_t1)
        arr_t2 = geo.read_raster_array(image_t2)
        min_c = min(arr_t1.shape[0], arr_t2.shape[0])
        arr_t1, arr_t2 = arr_t1[:min_c], arr_t2[:min_c]

    is_real, fallback_used, model_conf = True, False, 0.85
    with tracer.timed("changenet_inference"):
        try:
            model = load_changenet(PATHS.changenet / "changenet.pt", in_channels=min_c)
            probs = changenet_infer(model, arr_t1, arr_t2)
        except (FileNotFoundError, RuntimeError):
            if not FLAGS.allow_changenet_fallback:
                raise
            is_real, fallback_used, model_conf = False, True, 0.55
            probs = classical_change_fallback(arr_t1, arr_t2)

    with tracer.timed("threshold_selection"):
        thresh_used = threshold if threshold is not None else otsu_threshold(probs)

    with tracer.timed("affine_polygonization_and_area"):
        clusters = geo.mask_to_geo_clusters(probs, info_t1.transform, info_t1.crs_epsg,
                                             threshold=thresh_used)

    total_area_m2 = sum(c["area_m2"] for c in clusters)
    changed_px = int((probs >= thresh_used).sum())
    change_percent = round(100.0 * changed_px / probs.size, 2)

    features = [{
        "type": "Feature",
        "properties": {"cluster_id": c["cluster_id"], "area_m2": c["area_m2"], "area_ha": c["area_ha"]},
        "geometry": {"type": "Polygon", "coordinates": [c["ring_native_crs"]]},
    } for c in clusters]
    feature_collection = {"type": "FeatureCollection", "features": features}

    narrative = (
        f"Bi-temporal analysis detected {change_percent}% surface alteration across "
        f"{total_area_m2:,.0f} m² ({total_area_m2/10000:.2f} ha) in {len(clusters)} distinct "
        f"cluster(s)."
    )
    if query:
        narrative = f"{narrative} (query: \"{query}\")"

    reliability, factors = compute_reliability(
        model_confidence=model_conf, registration_quality=pair_check.overlap_fraction,
        gsd_resolution_rating=gsd_rating(info_t1.gsd_x, "change_detection"), fallback_used=fallback_used,
    )
    evidence = build_evidence(
        task="bitemporal_change_detection",
        model="Siamese ChangeNet + Affine Geometry Engine" if is_real
        else "Classical spectral-difference (Otsu) + Affine Geometry Engine",
        is_real_weights=is_real, fallback_used=fallback_used,
        inputs=[image_t1, image_t2], claim=narrative, spatial_evidence=feature_collection,
        metrics={
            "change_percent": change_percent, "total_area_m2": round(total_area_m2, 2),
            "total_area_ha": round(total_area_m2 / 10000, 4), "cluster_count": len(clusters),
            "threshold_used": round(float(thresh_used), 4), "overlap_fraction": pair_check.overlap_fraction,
        },
        reliability_score=reliability, reliability_factors=factors, tracer=tracer,
        warnings=pair_check.reasons + ([] if is_real else
            ["No ChangeNet checkpoint -- mask from classical spectral differencing, "
             "not a trained Siamese network."]),
    )
    return evidence.to_dict()


