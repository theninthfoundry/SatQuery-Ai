def run_captioning(image_path: str) -> dict:
    tracer = ProvenanceTracer()
    with tracer.timed("read_raster_info"):
        info = geo.read_raster_info(image_path)

    is_real, fallback_used, caption, model_conf = True, False, None, 0.85
    with tracer.timed("geochat_captioning_inference"):
        try:
            adapter = GeoChatAdapter()
            adapter.load()
            img = Image.open(image_path).convert("RGB")
            result = adapter.caption(img)
            adapter.unload()
            caption = result["caption"]
        except GeoChatUnavailable:
            if not FLAGS.allow_geochat_fallback:
                raise
            is_real, fallback_used, model_conf = False, True, 0.4
            caption = _caption_heuristic_fallback(image_path)

    reliability, factors = compute_reliability(
        model_confidence=model_conf, registration_quality=1.0,
        gsd_resolution_rating=gsd_rating(info.gsd_x, "captioning"), fallback_used=fallback_used,
    )
    evidence = build_evidence(
        task="scene_captioning", model="GeoChat-7B (4-bit NF4)" if is_real else "Heuristic statistics fallback",
        is_real_weights=is_real, fallback_used=fallback_used,
        inputs=[image_path], claim=caption, spatial_evidence=None,
        metrics={"width": info.width, "height": info.height, "bands": info.count},
        reliability_score=reliability, reliability_factors=factors, tracer=tracer,
    )
    return evidence.to_dict()


def _caption_heuristic_fallback(image_path: str) -> str:
    arr = geo.read_raster_array(image_path)
    bands = BandMap()
    veg_frac, water_frac = 0.0, 0.0
    try:
        from backend.models.dofa.adapter import ndwi, ndbi
        water_frac = float((ndwi(arr, bands) > 0.2).mean())
        veg_frac = float((ndbi(arr, bands) < -0.1).mean())
    except Exception:
        pass
    return (
        f"[Fallback -- no GeoChat weights loaded] Estimated composition from spectral "
        f"indices: ~{water_frac*100:.1f}% water-like pixels, ~{veg_frac*100:.1f}% "
        f"vegetation-like pixels. Load GeoChat-7B for a full semantic scene description."
    )


