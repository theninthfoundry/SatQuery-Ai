# 5. Optical + SAR fusion
# ---------------------------------------------------------------------------

def run_fusion_optical_sar(optical_path: str, sar_path: str, query: Optional[str] = None) -> dict:
    tracer = ProvenanceTracer()
    with tracer.timed("read_raster_info"):
        info_opt = geo.read_raster_info(optical_path)
        info_sar = geo.read_raster_info(sar_path)

    with tracer.timed("validate_pair_overlap"):
        pair_check = geo.validate_bitemporal_pair(info_opt, info_sar, min_overlap=0.6)
        # not truly "bitemporal" but the same overlap/CRS/GSD check applies

    with tracer.timed("read_raster_arrays"):
        arr_opt = geo.read_raster_array(optical_path)
        sar_raw = geo.read_raster_array(sar_path)[0]
        # Storage convention (see scripts/seed_demo_data.py and any SAR
        # ingestion step): sigma-nought dB is stored as uint16 via
        # (db + 30) * 1000 to avoid float rasters for the demo pipeline.
        # Real Sentinel-1 GRD products are typically float32 dB already --
        # detect and skip descaling if the array already looks like dB
        # (i.e. has negative or small-magnitude values).
        if sar_raw.max() > 1000:  # heuristic: looks like the scaled uint16 convention
            sar = sar_raw / 1000.0 - 30.0
        else:
            sar = sar_raw

    is_real, fallback_used, model_conf = False, True, 0.6  # DOFA real path is a documented stub above
    with tracer.timed("dofa_or_fallback_fusion"):
        fusion = classical_fusion_fallback(arr_opt, sar)

    with tracer.timed("polygonize_agreement_layers"):
        water_clusters = geo.mask_to_geo_clusters(fusion.water_agreement, info_opt.transform,
                                                    info_opt.crs_epsg, threshold=0.5)
        builtup_clusters = geo.mask_to_geo_clusters(fusion.builtup_agreement, info_opt.transform,
                                                      info_opt.crs_epsg, threshold=0.5)
        disagreement_clusters = geo.mask_to_geo_clusters(fusion.water_disagreement, info_opt.transform,
                                                           info_opt.crs_epsg, threshold=0.5)

    def _fc(clusters, label):
        return [{
            "type": "Feature",
            "properties": {"layer": label, "cluster_id": c["cluster_id"], "area_ha": c["area_ha"]},
            "geometry": {"type": "Polygon", "coordinates": [c["ring_native_crs"]]},
        } for c in clusters]

    feature_collection = {
        "type": "FeatureCollection",
        "features": _fc(water_clusters, "water_confirmed") + _fc(builtup_clusters, "builtup_confirmed")
        + _fc(disagreement_clusters, "optical_only_flag_possible_cloud_shadow"),
    }

    water_area_ha = sum(c["area_ha"] for c in water_clusters)
    built_area_ha = sum(c["area_ha"] for c in builtup_clusters)
    flagged_ha = sum(c["area_ha"] for c in disagreement_clusters)

    narrative = (
        f"Cross-modal analysis confirms {water_area_ha:.2f} ha of water and "
        f"{built_area_ha:.2f} ha of built-up area where optical and SAR agree. "
        f"{flagged_ha:.2f} ha flagged as optical-only water signal (possible cloud "
        f"shadow false alarm, unconfirmed by radar backscatter). Cross-modal "
        f"consistency index: {fusion.cross_modal_consistency_index:.0%}."
    )
    if query:
        narrative = f"{narrative} (query: \"{query}\")"

    reliability, factors = compute_reliability(
        model_confidence=model_conf, registration_quality=pair_check.overlap_fraction,
        gsd_resolution_rating=gsd_rating(info_opt.gsd_x, "fusion"), fallback_used=fallback_used,
    )
    evidence = build_evidence(
        task="optical_sar_fusion", model="Classical NDWI/NDBI + SAR backscatter thresholding "
        "(DOFA checkpoint not loaded)",
        is_real_weights=is_real, fallback_used=fallback_used,
        inputs=[optical_path, sar_path], claim=narrative, spatial_evidence=feature_collection,
        metrics={
            "water_confirmed_ha": round(water_area_ha, 4),
            "builtup_confirmed_ha": round(built_area_ha, 4),
            "optical_only_flagged_ha": round(flagged_ha, 4),
            "cross_modal_consistency_index": fusion.cross_modal_consistency_index,
        },
        reliability_score=reliability, reliability_factors=factors, tracer=tracer,
        warnings=["DOFA checkpoint not wired in -- see backend/models/dofa/adapter.py; "
                  "results use classical spectral-index + SAR-threshold fusion."],
    )
    return evidence.to_dict()


